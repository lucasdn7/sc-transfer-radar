export function isSantaCatarinaMunicipality(name: string): boolean {
  const normalized = name.normalize("NFD").replace(/[\u0300-\u036f]/g, "")
    .toLowerCase().replace(/[^a-z0-9]/g, "");
  return SANTA_CATARINA_MUNICIPALITIES.has(normalized);
}
